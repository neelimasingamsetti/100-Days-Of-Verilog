module Dec4_16(a,b,c,d,Y);
  input a,b,c,d;
  output reg [15:0] Y;
  always@(*)begin
    Y=16'b0000000000000000;
    
    case ({a,b,c,d})
      4'b0000: Y[0]=1;
      4'b0001: Y[1]=1;
      4'b0010: Y[2]=1;
      4'b0011: Y[3]=1;
      4'b0100: Y[4]=1;
      4'b0101: Y[5]=1;
      4'b0110: Y[6]=1;
      4'b0111: Y[7]=1;
      4'b1000: Y[8]=1;
      4'b1001: Y[9]=1;
      4'b1010: Y[10]=1;
      4'b1011: Y[11]=1;
      4'b1100: Y[12]=1;
      4'b1101: Y[13]=1;
      4'b1110: Y[14]=1;
      4'b1111: Y[15]=1;
    endcase
  end
endmodule
    
      
